// Distinct ids can normalise to the same component name ("1inch" and
// "oneinch" both become OneInchIcon) — that would emit duplicate exports in
// a barrel, surfacing as an opaque tsc error. Fail with the colliding pair.
function assertUniqueComponentNames(
  assets: readonly { id: string }[],
  kind: string,
  suffix = 'Icon',
) {
  const seen = new Map<string, string>()
  for (const a of assets) {
    const name = createComponentName(a.id, suffix)
    const prior = seen.get(name)
    if (prior !== undefined) {
      throw new Error(
        `Component name collision in ${kind}: "${prior}" and "${a.id}" both generate ${name}`,
      )
    }
    seen.set(name, a.id)
  }
}

