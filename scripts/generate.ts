// Lazy dispatchers (per-type, first-char keyed) + sub-shard files + eager map
function emitLazyType(
  assets: (TokenAsset | ChainAsset | BrandAsset)[],
  dirName: 'tokens' | 'chains' | 'brands',
) {
  const { dispatcher, shards } = generateLazyType(assets, dirName)
  emit(resolve(REACT_GEN, `lazy/${dirName}.ts`), dispatcher)
  for (const [fileKey, content] of shards) {
    emit(resolve(REACT_GEN, `lazy/${dirName}/${fileKey}.ts`), content)
  }
}
