// Emits the two variant files + the combined component for one asset/frame.
function emitComponentTrio(dir: string, fileBase: string, spec: ComponentSpec) {
  emit(resolve(dir, `${fileBase}.full.tsx`), generateVariantFile(spec, 'full'))
  emit(resolve(dir, `${fileBase}.mono.tsx`), generateVariantFile(spec, 'mono'))
  emit(
    resolve(dir, `${fileBase}.tsx`),
    generateCombinedComponent(spec, fileBase),
  )
}

