// A lazy icon resolves through THREE steps now: per-type dispatcher -> shard
// file (keyed by the id's first char) -> per-variant icon chunk. The dispatcher
// is small (one thunk per distinct first char) and stays the dynamic-import
// entry point; the heavy id -> { full, mono } maps live in the shard files, so
// the first lazy render only downloads the one shard the id falls into instead
// of the whole type's map.
//
// Fan-out: a type with <= SHARD_FANOUT_THRESHOLD lazy ids emits ONE shard file
// ('_all') and every present first-char key points at it (multiple keys -> one
// file is fine and keeps lazy-icons.ts trivial). Above the threshold, one shard
// file per first character. Every import specifier is a static string literal
// (no template paths) so the bundler can code-split.
const SHARD_FANOUT_THRESHOLD = 64
const SINGLE_SHARD_KEY = '_all'

function shardKey(id: string): string {
  return id[0]
}

// Returns the dispatcher module plus the shard files for one type. The lazy
// assets are partitioned by first char; below threshold they all collapse into
// one '_all' file pointed at by every present first-char key.
function generateLazyType(
  assets: (TokenAsset | ChainAsset | BrandAsset)[],
  dirName: 'tokens' | 'chains' | 'brands',
): { dispatcher: string; shards: Map<string, string> } {
  const lazy = assets.filter((a) => !a.bundle)

  // file key -> ids in that shard file.
  const fileGroups = new Map<string, string[]>()
  // first-char key -> file key it dispatches to.
  const keyToFile = new Map<string, string>()

  if (lazy.length <= SHARD_FANOUT_THRESHOLD) {
    const ids = lazy.map((a) => a.id)
    if (ids.length > 0) {
      fileGroups.set(SINGLE_SHARD_KEY, ids)
      for (const a of lazy) {
        keyToFile.set(shardKey(a.id), SINGLE_SHARD_KEY)
      }
    }
  } else {
    for (const a of lazy) {
      const key = shardKey(a.id)
      // One file per first char; the file key IS the first char.
      keyToFile.set(key, key)
      const group = fileGroups.get(key) ?? []
      group.push(a.id)
      fileGroups.set(key, group)
    }
  }

  const dispatcher = generateLazyDispatcher(dirName, keyToFile)

  const shards = new Map<string, string>()
  for (const [fileKey, ids] of fileGroups) {
    shards.set(fileKey, generateLazyShardFile(dirName, ids))
  }

  return { dispatcher, shards }
}

// The per-type dispatcher: SHARD_IMPORTS maps a first-char key to a thunk that
// statically imports the shard file holding that key's ids. Lazy-icons.ts
// indexes this by `id[0]`.
function generateLazyDispatcher(
  dirName: 'tokens' | 'chains' | 'brands',
  keyToFile: Map<string, string>,
): string {
  const lines: string[] = [
    '// Auto-generated by scripts/generate.ts - DO NOT EDIT',
    "import type { ComponentType } from 'react'",
    "import type { IconProps } from '../../icon-props'",
    '',
    'type Loader = () => Promise<{ default: ComponentType<IconProps> }>',
    'type Shard = {',
    '  ICON_IMPORTS: Record<string, { full: Loader; mono: Loader }>',
    '}',
    '',
    'export const SHARD_IMPORTS: Record<string, () => Promise<Shard>> = {',
  ]
  // Sort keys for stable output.
  for (const key of [...keyToFile.keys()].sort()) {
    const file = keyToFile.get(key)!
    lines.push(
      `  ${JSON.stringify(key)}: () => import('./${dirName}/${file}'),`,
    )
  }
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

// One shard file: the id -> per-variant import-thunk map for the ids that fall
// into it. Each id maps to { full, mono } thunks so a mono-only render only
// ever downloads the mono variant chunk.
function generateLazyShardFile(
  dirName: 'tokens' | 'chains' | 'brands',
  ids: string[],
): string {
  const lines: string[] = [
    '// Auto-generated by scripts/generate.ts - DO NOT EDIT',
    "import type { ComponentType } from 'react'",
    "import type { IconProps } from '../../../icon-props'",
    '',
    'type Loader = () => Promise<{ default: ComponentType<IconProps> }>',
    '',
    'export const ICON_IMPORTS: Record<',
    '  string,',
    '  { full: Loader; mono: Loader }',
    '> = {',
  ]
  for (const id of ids) {
    lines.push(
      `  ${JSON.stringify(id)}: { full: () => import('../../${dirName}/${id}.full'), mono: () => import('../../${dirName}/${id}.mono') },`,
    )
  }
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

function generateEagerMap(
  tokens: TokenAsset[],
  chains: ChainAsset[],
  brands: BrandAsset[],
): string {
  const eagerTokens = tokens.filter((t) => t.bundle)
  const eagerChains = chains.filter((c) => c.bundle)
  const eagerBrands = brands.filter((b) => b.bundle)

  const lines: string[] = [
    '// Auto-generated by scripts/generate.ts - DO NOT EDIT',
    "import type { ComponentType } from 'react'",
    "import type { IconProps } from '../icon-props'",
    '',
  ]

  // Alias every local binding by type. createComponentName is unique only
  // WITHIN a type (assertUniqueComponentNames), but this one module imports
  // all three types — a cross-type duplicate id (token `eth` + chain `eth`,
  // both bundled) or two ids that converge on one component name across types
  // would otherwise emit the same import identifier twice and fail to compile.
  // `Token`/`Chain`/`Brand` + the per-type-unique name is globally unique.
  const local = (type: 'Token' | 'Chain' | 'Brand', id: string) =>
    `${type}_${createComponentName(id)}`

  // Static imports
  for (const t of eagerTokens) {
    lines.push(
      `import { ${createComponentName(t.id)} as ${local('Token', t.id)} } from './tokens/${t.id}'`,
    )
  }
  for (const c of eagerChains) {
    lines.push(
      `import { ${createComponentName(c.id)} as ${local('Chain', c.id)} } from './chains/${c.id}'`,
    )
  }
  for (const b of eagerBrands) {
    lines.push(
      `import { ${createComponentName(b.id)} as ${local('Brand', b.id)} } from './brands/${b.id}'`,
    )
  }

  lines.push('')
  lines.push(
    'export const EAGER_ICONS: Record<string, ComponentType<IconProps>> = {',
  )

  for (const t of eagerTokens) {
    lines.push(`  ${JSON.stringify(`token:${t.id}`)}: ${local('Token', t.id)},`)
  }
  for (const c of eagerChains) {
    lines.push(`  ${JSON.stringify(`chain:${c.id}`)}: ${local('Chain', c.id)},`)
  }
  for (const b of eagerBrands) {
    lines.push(`  ${JSON.stringify(`brand:${b.id}`)}: ${local('Brand', b.id)},`)
  }

  lines.push('}')
  lines.push('')

  return lines.join('\n')
}

// --- Output helpers ---

const aliasWarnings: string[] = []
const sameTypeCollisions: AliasCollision[] = []

// --- Manifest-diff write phase ---
//
// Replaces the old "wipe the dir up front" cleanup. Wiping defeated the
// skip-identical optimisation (every file looked new). Instead: collect the
// set of generated files currently on disk under the gen roots, write only
// the ones whose content changed, and delete the ones we no longer produce.
function listGeneratedFiles(root: string): string[] {
  if (!existsSync(root)) return []
  const out: string[] = []
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = resolve(dir, entry.name)
      if (entry.isDirectory()) walk(p)
      else out.push(p)
    }
  }
  walk(root)
  return out
}

function writeOutputs(): { written: number; skipped: number; removed: number } {
  // Ensure parent dirs exist for every output.
  const dirs = new Set<string>()
  for (const path of outputs.keys()) {
    dirs.add(resolve(path, '..'))
  }
  for (const dir of dirs) mkdirSync(dir, { recursive: true })

  let written = 0
  let skipped = 0
  for (const [path, content] of outputs) {
    // Skip writing files whose on-disk content is already identical, to
    // avoid mtime churn that retriggers watchers/build caches.
    if (existsSync(path) && statSync(path).isFile()) {
      try {
        if (readFileSync(path, 'utf-8') === content) {
          skipped++
          continue
        }
      } catch {
        // fall through to write
      }
    }
    writeFileSync(path, content)
    written++
  }

  // Remove stale generated files no longer produced.
  let removed = 0
  for (const root of [CORE_GEN, REACT_GEN]) {
    for (const existing of listGeneratedFiles(root)) {
      if (!outputs.has(existing)) {
        rmSync(existing, { force: true })
        removed++
      }
    }
  }

  // Prune now-empty directories left behind by removals.
  for (const root of [CORE_GEN, REACT_GEN]) {
    pruneEmptyDirs(root)
  }

  return { written, skipped, removed }
}

function pruneEmptyDirs(dir: string) {
  if (!existsSync(dir)) return
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) pruneEmptyDirs(resolve(dir, entry.name))
  }
  if (readdirSync(dir).length === 0) {
    rmSync(dir, { recursive: true, force: true })
  }
}

