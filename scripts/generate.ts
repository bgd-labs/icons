// --- In-memory output accumulation ---
//
// Every generated file is built into this map first. Nothing is written
// until the whole run is known-good: a fatal alias collision aborts BEFORE
// any write, so a failed generate can never leave poisoned src/generated/
// that a later build compiles.
const outputs = new Map<string, string>()

function emit(path: string, content: string) {
  outputs.set(path, content)
}

// --- Utilities ---

function escapeForTemplate(s: string): string {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$')
}

function toSafeVarName(s: string): string {
  let result = s.replace(/[-_](\w)/g, (_, c) => c.toUpperCase())
  result = result.replace(/[^a-zA-Z0-9_$]/g, '')
  if (/^\d/.test(result)) {
    result = '_' + result
  }
  if (!/^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(result)) {
    throw new Error(
      `Cannot create safe JS variable name from "${s}" (got "${result}")`,
    )
  }
  return result
}

// --- Generate Core Package ---

function generateCoreMeta(
  tokens: TokenAsset[],
  chains: ChainAsset[],
  brands: BrandAsset[],
) {
  // placeholderColor is the dominant colour of the full SVG; absent means the
  // glyph had no single dominant colour. The encoder collapses it to empty
  // when it equals brandColor, so equal-colour icons cost one field, not two.
  const pc = (svg: string): string | undefined =>
    dominantColor(svg) ?? undefined

  const tokenRows: MetaRowInput[] = tokens.map((t) => ({
    id: t.id,
    name: t.name,
    brandColor: t.brandColor,
    placeholderColor: pc(t.fullSvg),
    symbol: t.symbol,
  }))
  const chainRows: MetaRowInput[] = chains.map((c) => ({
    id: c.id,
    name: c.name,
    brandColor: c.brandColor,
    placeholderColor: pc(c.fullSvg),
    chainId: c.chainId,
  }))
  const brandRows: MetaRowInput[] = brands.map((b) => ({
    id: b.id,
    name: b.name,
    brandColor: b.brandColor,
    placeholderColor: pc(b.fullSvg),
  }))

  // Each per-type table is one control-char-framed string; the decoder rebuilds
  // the same Record<IdentityKey, IconMeta> at module init. JSON.stringify emits
  // the framing control chars as \uXXXX escapes inside a plain double-quoted
  // JS string literal — safe, with no template-literal escaping hazards.
  return [
    '// Auto-generated by scripts/generate.ts - DO NOT EDIT',
    '',
    "import type { IconMeta, IconType } from '../types'",
    "import type { IdentityKey } from '../internal/identity'",
    "import { decodeMeta } from '../internal/codec'",
    '',
    `const ENCODED: Record<IconType, string> = {`,
    `  token: ${JSON.stringify(encodeMetaTable(tokenRows))},`,
    `  chain: ${JSON.stringify(encodeMetaTable(chainRows))},`,
    `  brand: ${JSON.stringify(encodeMetaTable(brandRows))},`,
    `}`,
    '',
    'export const META: Record<IdentityKey, IconMeta> = decodeMeta(ENCODED)',
    '',
  ].join('\n')
}

// String-literal unions of every shipped canonical id. Exported for
// consumers that want compile-time exhaustiveness (icon pickers, config
// maps) — the resolver functions intentionally keep accepting arbitrary
// strings, since aliases/symbols/chain ids are part of the input surface.
// Named *IconId (not ChainId) because IconMeta.chainId is the NUMERIC
// chain id — a string union called ChainId would be a footgun.
function generateCoreIds(
  tokens: TokenAsset[],
  chains: ChainAsset[],
  brands: BrandAsset[],
) {
  const union = (assets: { id: string }[]): string =>
    assets.length === 0
      ? ' never'
      : '\n' + assets.map((a) => `  | ${JSON.stringify(a.id)}`).join('\n')

  return [
    '// Auto-generated by scripts/generate.ts - DO NOT EDIT',
    '',
    `export type TokenIconId =${union(tokens)}`,
    '',
    `export type ChainIconId =${union(chains)}`,
    '',
    `export type BrandIconId =${union(brands)}`,
    '',
    'export type IconId = TokenIconId | ChainIconId | BrandIconId',
    '',
  ].join('\n')
}

function generateCoreAliases(cat: Catalogue) {
  const identityIndexes = buildIdentityIndexes(toIdentityAssets(cat))
  aliasWarnings.push(...identityIndexes.warnings)
  sameTypeCollisions.push(
    ...identityIndexes.collisions.filter((c) => c.kept.type === c.dropped.type),
  )

  // Only the per-type maps are encoded; the cross-type map is derived at
  // module init (internal/identity.ts buildGlobalAliases) so every alias ships
  // exactly once. Each row drops the id's own normalized self-key (the decoder
  // re-adds it) and carries whatever extra keys buildIdentityIndexes produced
  // (symbol/chainId-derived + authored aliases) verbatim — the decode never
  // re-derives, keeping generate-time the single source of truth.
  return [
    '// Auto-generated by scripts/generate.ts - DO NOT EDIT',
    '',
    "import type { IconType } from '../types'",
    "import { decodeAliases } from '../internal/codec'",
    '',
    `const ENCODED: Record<IconType, string> = {`,
    `  token: ${JSON.stringify(encodeAliasTable(identityIndexes.typeAliases.token))},`,
    `  chain: ${JSON.stringify(encodeAliasTable(identityIndexes.typeAliases.chain))},`,
    `  brand: ${JSON.stringify(encodeAliasTable(identityIndexes.typeAliases.brand))},`,
    `}`,
    '',
    'export const TYPE_ALIASES: Record<IconType, Record<string, string>> =',
    '  decodeAliases(ENCODED)',
    '',
  ].join('\n')
}

function generateCoreSvgExports(
  assets: (TokenAsset | ChainAsset | BrandAsset)[],
  category: string,
) {
  const lines: string[] = [
    '// Auto-generated by scripts/generate.ts - DO NOT EDIT',
    '',
    "import type { IconVariant } from '../../types'",
    '',
  ]

  for (const a of assets) {
    const camel = toSafeVarName(a.id)
    lines.push(
      `export const ${camel}Full = \`${escapeForTemplate(a.fullSvg.trim())}\``,
    )
    lines.push(
      `export const ${camel}Mono = \`${escapeForTemplate(a.monoSvg.trim())}\``,
    )
    lines.push('')
  }

  // Lookup map for function access. NOTE: the map pins every icon of the
  // type — importing the getter retains the whole shard. Per-icon named
  // consts above stay tree-shakeable.
  lines.push(
    `const SVG_MAP: Record<string, { full: string; mono: string }> = {`,
  )
  for (const a of assets) {
    const camel = toSafeVarName(a.id)
    lines.push(
      `  ${JSON.stringify(a.id)}: { full: ${camel}Full, mono: ${camel}Mono },`,
    )
  }
  lines.push('}')
  lines.push('')
  lines.push(
    `export function get${capitalize(category)}Svg(id: string, variant: IconVariant = 'full'): string | null {`,
  )
  lines.push(`  const entry = SVG_MAP[id]`)
  lines.push(`  return entry ? entry[variant] : null`)
  lines.push('}')
  lines.push('')

  return lines.join('\n')
}

// --- Generate React Package ---

type Variant = 'full' | 'mono'

interface ComponentSpec {
  // The SVG markup for each variant.
  fullSvg: string
  monoSvg: string
  // Component identity + aria.
  componentName: string
  ariaLabel: string
  // The props type imported per emitted file.
  propsType: 'IconProps' | 'FrameIconProps'
}

// displayName MUST be gated behind NODE_ENV: the barrel entry and shared
// eager chunks are single modules after bundling, and an unconditional
// `X.displayName = ...` is a top-level side effect that forces a consumer's
// bundler to keep EVERY component in any module it touches — importing one
// icon from the barrel would drag all of its chunk-mates along. With the
// gate, production builds replace NODE_ENV, the branch goes dead, and the
// unreferenced components tree-shake away (fixtures/consumer/tree-shake.mjs
// guards this). The `typeof process` check mirrors src/env.d.ts: no-bundler
// ESM consumers (CDN) have no `process` and must not throw.
function displayNameLines(componentName: string): string[] {
  return [
    "if (typeof process !== 'undefined' && process.env.NODE_ENV !== 'production') {",
    `  ${componentName}.displayName = '${componentName}'`,
    '}',
  ]
}

// One variant SVG file: a forwardRef component whose default export contains
// ONLY this variant's markup, so a mono-only consumer's lazy chunk never
// downloads the full art (or vice versa). `mono` is destructured-and-
// discarded so it never lands on the DOM element. Mirrors the per-variant
// branch the combined component used to inline.
function generateVariantFile(spec: ComponentSpec, variant: Variant): string {
  const svg = variant === 'mono' ? spec.monoSvg : spec.fullSvg
  // SVG resource ids (clipPaths, gradients) must be unique per mounted
  // INSTANCE, not just per asset: url(#...) resolves document-wide to the
  // first match, so a second copy of the same icon — e.g. one in a hidden
  // drawer — hijacks the refs of every visible copy and blanks it. Icons
  // that define ids get a useId()-derived prefix baked into ids and refs.
  const { jsx: inner, idCount } = parameterizeIds(
    extractSvgInner(svgToJsx(svg)),
  )
  const viewBox = extractViewBox(svg) || '0 0 32 32'
  // Suffixed so React DevTools distinguishes the variant actually mounted
  // (the combined component renders one of the two).
  const variantName = `${spec.componentName}${capitalize(variant)}`

  let fillAttr: string
  if (variant === 'mono') {
    // Mono root fill: stroke-only art (outline glyphs / frame rings) must
    // keep fill="none" so shapes aren't filled solid; filled glyphs inherit
    // currentColor. A mono SVG that fills explicitly opts back in.
    const strokeOnly =
      /stroke="currentColor"/.test(svg) && !/fill="currentColor"/.test(svg)
    fillAttr = strokeOnly ? ' fill="none"' : ' fill="currentColor"'
  } else {
    // Preserve an explicit fill="none" on the full SVG root if present.
    fillAttr = /<svg[^>]*fill="none"/.test(svg) ? ' fill="none"' : ''
  }

  // `mono` is consumed by the combined component; here it is discarded so
  // it never reaches the DOM <svg>. Icons that define resource ids get a
  // per-instance prefix: useId() is unique per mount and SSR-stable, and the
  // sanitize strips React's delimiter characters (`:` / `«»`), which are not
  // safe inside an unquoted CSS url() token.
  const bodyLines =
    idCount > 0
      ? [
          '  ({ mono: _mono, size = 32, ...props }, ref) => {',
          "    const uid = useId().replace(/[^a-zA-Z0-9_-]/g, '')",
          '    return (',
          `      <svg ref={ref} width={size} height={size} viewBox="${viewBox}"${fillAttr} role="img" aria-label="${spec.ariaLabel}" {...props}>`,
          `        ${inner}`,
          '      </svg>',
          '    )',
          '  },',
        ]
      : [
          '  ({ mono: _mono, size = 32, ...props }, ref) => (',
          `    <svg ref={ref} width={size} height={size} viewBox="${viewBox}"${fillAttr} role="img" aria-label="${spec.ariaLabel}" {...props}>`,
          `      ${inner}`,
          '    </svg>',
          '  ),',
        ]

  return [
    '// Auto-generated by scripts/generate.ts - DO NOT EDIT',
    idCount > 0
      ? "import { forwardRef, useId } from 'react'"
      : "import { forwardRef } from 'react'",
    `import type { ${spec.propsType} } from '../../icon-props'`,
    '',
    // PURE annotation: forwardRef() is opaque to bundlers, and chunk-mates
    // inside one shared module are only droppable when the init is provably
    // side-effect-free. Together with the NODE_ENV displayName gate this is
    // what makes single-icon imports tree-shake (see tree-shake.mjs fixture).
    `const ${variantName} = /* @__PURE__ */ forwardRef<SVGSVGElement, ${spec.propsType}>(`,
    ...bodyLines,
    ')',
    ...displayNameLines(variantName),
    '',
    `export default ${variantName}`,
    '',
  ].join('\n')
}

// The combined named component: a thin forwardRef that statically imports
// both variant components and renders one based on `mono`. No SVG markup is
// duplicated here — it lives in the two variant files.
function generateCombinedComponent(
  spec: ComponentSpec,
  fileBase: string,
): string {
  return [
    '// Auto-generated by scripts/generate.ts - DO NOT EDIT',
    "import { forwardRef } from 'react'",
    `import type { ${spec.propsType} } from '../../icon-props'`,
    `import ${spec.componentName}Full from './${fileBase}.full'`,
    `import ${spec.componentName}Mono from './${fileBase}.mono'`,
    '',
    `export const ${spec.componentName} = /* @__PURE__ */ forwardRef<SVGSVGElement, ${spec.propsType}>(`,
    '  ({ mono = false, ...props }, ref) =>',
    `    mono ? (`,
    `      <${spec.componentName}Mono ref={ref} {...props} />`,
    `    ) : (`,
    `      <${spec.componentName}Full ref={ref} {...props} />`,
    `    ),`,
    ')',
    ...displayNameLines(spec.componentName),
    '',
  ].join('\n')
}

